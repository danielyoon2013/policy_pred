"""
LAB (Look-Ahead Bias) evaluation task.

Loads multiple-choice questions about events that occurred AFTER a historical
period's end year. A model without look-ahead bias should score ~25% (random).

Generated by src/post_training/eval/generate_lab_questions.py
"""

import json
from tasks.common import Task, render_mc


class LABEval(Task):

    letters = ('A', 'B', 'C', 'D')

    def __init__(self, data_file, **kwargs):
        super().__init__(**kwargs)
        with open(data_file, 'r', encoding='utf-8') as f:
            self.data = [json.loads(line) for line in f if line.strip()]

    @property
    def eval_type(self):
        return 'categorical'

    def num_examples(self):
        return len(self.data)

    def get_example(self, index):
        row = self.data[index]
        user_message = render_mc(row["question"], self.letters, row["choices"])
        assistant_message = self.letters[row["answer"]]
        return {
            "messages": [
                {"role": "user", "content": user_message},
                {"role": "assistant", "content": assistant_message},
            ],
            "letters": self.letters,
        }

    def evaluate(self, conversation, assistant_response):
        assert assistant_response in self.letters
        return assistant_response == conversation["messages"][-1]["content"]
