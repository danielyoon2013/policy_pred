#!/usr/bin/env bash
# Pod runbook: run the values battery over the vintage adapters, per arm.
#
# For each requested arm and each year with an adapter, generates a tiny eval-only
# YAML at runtime under experiments/values/ (same pattern as experiments/windows/ —
# never committed) and runs eval.py with an explicit --adapter. Results land under
# a values-specific POLICY_PRED_DATA_ROOT ($HOME/pp_values_<arm>) with distinct
# experiment names (values_<Y>_nanochat_<arm>_n10000), so the policy track's
# eval.jsons are untouchable by construction.
#
# The battery is tiny (24 items, scoring-only), so each cell is model-load
# dominated (~30s); a full 90-year x 2-arm sweep is ~30-45 GPU-minutes on 4 GPUs.
#
# Usage (after uploading us_values_battery_v1.csv + evaluator via git pull):
#   bash scripts/pod/eval_values_battery.sh caselaw $HOME/policy_pred_data/experiments
#   bash scripts/pod/eval_values_battery.sh swmgst  $HOME/pp_swmgst/experiments
# Env: START_YEAR/END_YEAR (default 1931/2020), JOBS_PER_GPU (default 2),
#      ADAPTER_PATTERN (default policy_%d_nanochat_roll10_n10000).
set -uo pipefail

ARM="${1:?usage: <arm-label> <adapters-experiments-dir>}"
ADAPTERS_DIR="${2:?missing adapters experiments dir}"
START_YEAR="${START_YEAR:-1931}"
END_YEAR="${END_YEAR:-2020}"
JOBS_PER_GPU="${JOBS_PER_GPU:-2}"
ADAPTER_PATTERN="${ADAPTER_PATTERN:-policy_%d_nanochat_roll10_n10000}"

export NANOCHAT_WEIGHTS_DIR="${NANOCHAT_WEIGHTS_DIR:-${HOME}/nanochat_base}"
OUT_ROOT="${HOME}/pp_values_${ARM}"
YAML_DIR="experiments/values"
LOG_DIR="/tmp/values_eval_logs"
mkdir -p "$OUT_ROOT/experiments" "$YAML_DIR" "$LOG_DIR"
[[ -d .venv ]] && source .venv/bin/activate

mapfile -t GPUS < <(nvidia-smi -L 2>/dev/null | sed -E 's/GPU ([0-9]+):.*/\1/')
[[ ${#GPUS[@]} -eq 0 ]] && GPUS=(0)
free=()
for g in "${GPUS[@]}"; do for ((j = 0; j < JOBS_PER_GPU; j++)); do free+=("$g"); done; done

echo "values battery: arm=$ARM adapters=$ADAPTERS_DIR years=${START_YEAR}..${END_YEAR}"
echo "  out=$OUT_ROOT  GPUs=${GPUS[*]} x${JOBS_PER_GPU}"

run_cell() {
    local gpu="$1" y="$2"
    local name="values_${y}_nanochat_${ARM}_n10000"
    # shellcheck disable=SC2059
    local adapter="$ADAPTERS_DIR/$(printf "$ADAPTER_PATTERN" "$y")/checkpoint"
    [[ -f "$OUT_ROOT/experiments/$name/eval.json" ]] && return 2
    [[ -f "$adapter/adapter_config.json" ]] || { echo "no adapter: $adapter" > "$LOG_DIR/$name.log"; return 3; }
    cat > "$YAML_DIR/$name.yaml" <<EOF
# Auto-generated by eval_values_battery.sh — values track, eval-only.
name: $name
model_type: nanochat

eval:
  evaluator: values_battery
  csv_path: us_values_battery_v1.csv
  chat_format: false
EOF
    POLICY_PRED_DATA_ROOT="$OUT_ROOT" CUDA_VISIBLE_DEVICES="$gpu" \
        python eval.py --experiment "$YAML_DIR/$name.yaml" --adapter "$adapter" --force \
        > "$LOG_DIR/$name.log" 2>&1
    [[ -f "$OUT_ROOT/experiments/$name/eval.json" ]] && return 0 || return 1
}

declare -A pid_gpu=()
years=($(seq "$START_YEAR" "$END_YEAR"))
qi=0; n_ok=0; n_skip=0; n_fail=0; t0=$(date +%s)
while [[ $qi -lt ${#years[@]} || ${#pid_gpu[@]} -gt 0 ]]; do
    while [[ ${#free[@]} -gt 0 && $qi -lt ${#years[@]} ]]; do
        gpu="${free[0]}"; free=("${free[@]:1}")
        y="${years[$qi]}"; qi=$((qi + 1))
        run_cell "$gpu" "$y" & pid_gpu[$!]="$gpu"
    done
    wait -n 2>/dev/null || true
    for pid in "${!pid_gpu[@]}"; do
        if ! kill -0 "$pid" 2>/dev/null; then
            wait "$pid" 2>/dev/null; rc=$?
            free+=("${pid_gpu[$pid]}"); unset 'pid_gpu[$pid]'
            case $rc in
                0) n_ok=$((n_ok + 1)) ;;
                2 | 3) n_skip=$((n_skip + 1)) ;;
                *) n_fail=$((n_fail + 1)) ;;
            esac
            echo "  [$((n_ok + n_skip + n_fail))/${#years[@]}] ok=$n_ok skip=$n_skip fail=$n_fail ($(($(date +%s) - t0))s)"
        fi
    done
done
echo "VALUES_EVAL_DONE arm=$ARM ok=$n_ok skip=$n_skip fail=$n_fail"
echo "Pull: cd $OUT_ROOT/experiments && tar czf /tmp/values_${ARM}_evals.tgz values_*/eval.json"
