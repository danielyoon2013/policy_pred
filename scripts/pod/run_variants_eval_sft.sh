#!/usr/bin/env bash
# Pod runbook: variant-aware eval across the SFT-on-top chain, sharded
# across all available GPUs. Twin of run_variants_eval_sharded.sh, but
# targets policy_<Y>_naive_sft/ instead of policy_<Y>_naive/.
#
# Output: eval.json per year at policy_<Y>_naive_sft/eval.json — directly
# comparable to the CPT-only eval.json files (which we already pulled
# locally in chain_evals.tgz) for the Phase 5 trajectory plots.
#
# Usage:
#   bash scripts/pod/run_variants_eval_sft.sh                            # talkie, all years
#   bash scripts/pod/run_variants_eval_sft.sh 1935 1935                  # talkie smoke
#   VARIANT=nanochat bash scripts/pod/run_variants_eval_sft.sh           # nanochat all years
#   VARIANT=nanochat bash scripts/pod/run_variants_eval_sft.sh 1935 1935 # nanochat smoke
#
# VARIANT="" (default) targets policy_<Y>_naive_sft adapters.
# VARIANT="nanochat" targets policy_<Y>_naive_nanochat_sft adapters.
#
# Prerequisites:
#   - SFT-on-top adapters trained via train_policy_sft_on_top.sh
#   - SFT YAMLs at experiments/policy_<Y>_naive[_${VARIANT}]_sft.yaml
#     (auto-generated by the trainer)
#   - data_artifacts/question_variants/ extracted with 211 *.jsonl files
#
set -uo pipefail   # NOT -e — let one year's failure not kill the wave

START_YEAR="${1:-1931}"
END_YEAR="${2:-2020}"
VARIANT="${VARIANT:-}"                # "" = talkie, "nanochat" = nanochat chain
SUFFIX="${VARIANT:+_${VARIANT}}"      # "" or "_nanochat"

NUM_GPUS="${NUM_GPUS:-$(nvidia-smi -L 2>/dev/null | wc -l)}"
if [[ -z "$NUM_GPUS" || "$NUM_GPUS" -lt 1 ]]; then NUM_GPUS=1; fi

export TALKIE_WEIGHTS_DIR="${TALKIE_WEIGHTS_DIR:-${HOME}/talkie_base}"
export NANOCHAT_WEIGHTS_DIR="${NANOCHAT_WEIGHTS_DIR:-${HOME}/nanochat_base}"
export POLICY_PRED_DATA_ROOT="${POLICY_PRED_DATA_ROOT:-${HOME}/policy_pred_data}"

echo "============================================================="
echo "  Sharded variant-aware eval (SFT-on-top chain)"
echo "============================================================="
echo "  Year range:    ${START_YEAR}..${END_YEAR}"
echo "  Variant:       ${VARIANT:-talkie (default)}"
echo "  GPU shards:    ${NUM_GPUS}"
echo "  Logs:          /tmp/eval_sft${SUFFIX}_shard_<N>.log"
echo

if [[ -d ".venv" ]]; then
    # shellcheck disable=SC1091
    source .venv/bin/activate
fi

# --- Build the year list, skipping years whose SFT adapter or YAML is missing ---
years=()
for y in $(seq "$START_YEAR" "$END_YEAR"); do
    sft_name="policy_${y}_naive${SUFFIX}_sft"
    ckpt="${POLICY_PRED_DATA_ROOT}/experiments/${sft_name}/checkpoint"
    yaml="experiments/${sft_name}.yaml"
    if [[ ! -f "$ckpt/adapter_config.json" ]]; then
        echo "  SKIP year=$y (no SFT adapter at $ckpt)"
        continue
    fi
    if [[ ! -f "$yaml" ]]; then
        echo "  SKIP year=$y (no SFT YAML at $yaml)"
        continue
    fi
    years+=("$y")
done
n_total=${#years[@]}
if [[ "$n_total" -eq 0 ]]; then
    echo "Nothing to evaluate."
    exit 1
fi
echo "  Years to eval: $n_total"
echo

# --- Round-robin shard assignment so each GPU gets a mix of early/late years ---
declare -A shard_years
for i in "${!years[@]}"; do
    shard=$(( i % NUM_GPUS ))
    shard_years[$shard]+="${years[$i]} "
done

start_time=$(date +%s)
pids=()
for shard in $(seq 0 $((NUM_GPUS - 1))); do
    yrs="${shard_years[$shard]:-}"
    [[ -z "$yrs" ]] && continue
    log="/tmp/eval_sft${SUFFIX}_shard_${shard}.log"
    echo "  shard=$shard  GPU=$shard  years: $yrs  log: $log"
    (
        export CUDA_VISIBLE_DEVICES=$shard
        for y in $yrs; do
            sft_name="policy_${y}_naive${SUFFIX}_sft"
            yr_start=$(date +%s)
            python3 eval.py \
                --experiment "experiments/${sft_name}.yaml" \
                --evaluator policy_battery_variants \
                --force \
                > "${log}.${y}" 2>&1 \
                && status="OK" || status="FAIL"
            yr_elapsed=$(( $(date +%s) - yr_start ))
            echo "[shard=$shard] year=$y $status (${yr_elapsed}s)" | tee -a "$log"
        done
    ) &
    pids+=($!)
done

echo
echo "Launched ${#pids[@]} shards. Follow live progress with:"
echo "  tail -f /tmp/eval_sft${SUFFIX}_shard_*.log"
echo "Per-year logs: /tmp/eval_sft${SUFFIX}_shard_<S>.log.<YYYY>"
echo

n_failed=0
for pid in "${pids[@]}"; do
    if ! wait "$pid"; then
        n_failed=$((n_failed + 1))
    fi
done

total_elapsed=$(( $(date +%s) - start_time ))
n_eval_json=$(find "${POLICY_PRED_DATA_ROOT}/experiments" -path "*_naive${SUFFIX}_sft/eval.json" \
    -newer "/tmp/eval_sft${SUFFIX}_shard_0.log" 2>/dev/null | wc -l)

echo
echo "============================================================="
echo "  SFT-on-top sharded eval complete"
echo "============================================================="
echo "  Total wall time:   $((total_elapsed / 3600))h $((total_elapsed % 3600 / 60))m $((total_elapsed % 60))s"
echo "  Years requested:   $n_total"
echo "  eval.json written: $n_eval_json"
echo "  Failed shards:     $n_failed"
echo
echo "Pull results back to local with:"
echo "  cd $POLICY_PRED_DATA_ROOT/experiments"
echo "  tar czf /tmp/chain_sft${SUFFIX}_evals.tgz policy_*_naive${SUFFIX}_sft/eval.json"
echo "  # WinSCP /tmp/chain_sft${SUFFIX}_evals.tgz to local C:/tmp/"
